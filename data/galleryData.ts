import type { GalleryImage } from "@/types/gallery";

function photo(
  id: string,
  width: number,
  height: number,
  extra = "",
): string {
  const params = new URLSearchParams({
    auto: "format",
    fit: "crop",
    w: String(width),
    h: String(height),
    q: "80",
  });
  return `https://images.unsplash.com/${id}?${params.toString()}${extra}`;
}

